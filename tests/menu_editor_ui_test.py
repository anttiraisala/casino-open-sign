# Browser test of tools/menu-editor/index.html (Playwright).   python3 tests/menu_editor_ui_test.py [screenshot.png]
import os, sys, json
from playwright.sync_api import sync_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URL = 'file://' + ROOT + '/tools/menu-editor/' + os.environ.get('MENU_EDITOR_PAGE', 'index.html')
fails = []
def check(c, m):
    if not c: print('FAIL: ' + m); fails.append(m)
def eq(a, b, m): check(a == b, '%s (got %r, want %r)' % (m, a, b))
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_context(viewport={'width': 1500, 'height': 900}, color_scheme='dark').new_page()
    errs = []; pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
    pg.goto(URL); pg.wait_for_timeout(300)
    lcd = lambda: (pg.inner_text('#lcd0'), pg.inner_text('#lcd1'))
    eq(pg.inner_text('#status-msg'), 'valid', 'sample menu is valid')
    eq(lcd(), ('#0 Casino Closed', '← Customer right'), 'status page of the V2 sample')
    pg.select_option('#phys-program', '15'); pg.select_option('#phys-arrow', '1'); pg.select_option('#phys-casino', '1')
    eq(lcd()[0], '#F Casino Open  ', 'status row 0 after the switches')
    eq(lcd()[1], '→ Customer left ', 'status row 1 after the switches')
    pg.wait_for_timeout(3200)
    eq(lcd()[1], 'Change in 2:05  ', 'program F alternates to the countdown after 3 s')
    pg.click('#k-ok'); eq(lcd()[1], 'Controls       >', 'OK opens the menu at the first item')
    check(pg.inner_text('#lcd0').startswith('Menu') and pg.inner_text('#lcd0').rstrip().endswith('s'), 'countdown at the right edge: ' + pg.inner_text('#lcd0'))
    pg.click('#k-ok'); pg.click('#k-ok'); eq(lcd()[1].rstrip(), '🔒 F', 'a read-only value opens the view page with a padlock')
    pg.click('#k-back'); pg.click('#k-back'); eq(lcd()[1], 'Controls       >', 'BACK twice returns to the root')
    pg.click('#k-right'); pg.click('#k-ok'); pg.click('#k-ok')
    eq(lcd()[1].rstrip(), '> 1.000x', 'edit page of the frame speed')
    pg.click('#k-right'); eq(lcd()[1].rstrip(), '> 1.122x', 'one step up')
    pg.click('#k-shift'); pg.click('#k-right'); pg.click('#k-shift'); eq(lcd()[1].rstrip(), '> 3.564x', 'SHIFT makes the step ten times larger')
    pg.click('#k-ok'); check('speedFrame' in pg.inner_text('#log-ee') and '1: speedFrame' in pg.inner_text('#log-ee'), 'OK wrote the property to the EEPROM log')
    check('applySpeeds(speedFrame' in pg.inner_text('#log-cb'), 'callbacks are listed')
    pg.click('#btn-restart'); pg.wait_for_timeout(100)
    check(pg.inner_text('#lcd0').startswith('#F'), 'restart returns to the status page')
    pg.click('#k-ok'); pg.click('#k-right'); pg.click('#k-ok'); eq(lcd()[1].rstrip(), 'Frame speed: 3.5', 'the saved value survived the restart')
    pg.keyboard.press('Escape'); pg.keyboard.press('Escape'); pg.keyboard.press('Escape')
    # editing: change a property name and see it in the preview
    pg.click('button[data-tab="properties"]'); pg.click('#list div:has-text("speedFrame")')
    pg.fill('#f-name', 'Frame spd'); pg.press('#f-name', 'Tab'); pg.wait_for_timeout(100)
    check('Frame spd' in pg.evaluate("JSON.stringify(MenuEditor.S)"), 'name change is stored in the JSON')
    pg.click('button[data-tab="tree"]'); pg.click('#k-ok'); pg.click('#k-right'); pg.click('#k-ok'); eq(lcd()[1][:9], 'Frame spd', 'the new name shows on the display')
    pg.click('#k-back'); pg.click('#k-back')
    # an error: log scale with min 0
    pg.click('button[data-tab="properties"]'); pg.click('#list div:has-text("speedArrow")')
    pg.fill('#f-min', '0'); pg.press('#f-min', 'Tab'); pg.wait_for_timeout(100)
    check('log scale needs min' in pg.inner_text('#msgs'), 'error is listed: ' + pg.inner_text('#msgs')[:80])
    eq(pg.inner_text('#status-msg'), '1 error(s)', 'status shows the error count'); eq(pg.inner_text('#lcd0'), '(menu has errors)', 'preview is off while there are errors')
    pg.fill('#f-min', '0.25'); pg.press('#f-min', 'Tab'); pg.wait_for_timeout(100); eq(pg.inner_text('#status-msg'), 'valid', 'fixed again')
    # add a read-only quick-pick error through the JSON tab
    pg.click('button[data-tab="json"]')
    j = json.loads(pg.input_value('#json')); j['root']['items'].append({'preset': 'Bad', 'set': {'program': 3}})
    pg.fill('#json', json.dumps(j)); pg.click('#btn-json-apply'); pg.wait_for_timeout(100)
    check('read-only property program' in pg.inner_text('#msgs'), 'quick-pick on a read-only property is reported')
    # loop through the JSON tab
    j['root']['items'].pop(); j['common']['menus']['stripBrightness']['items'].append({'menuRef': 'stripBrightness'})
    pg.fill('#json', json.dumps(j)); pg.click('#btn-json-apply'); pg.wait_for_timeout(100); check('menu loop' in pg.inner_text('#msgs'), 'menu loop reported')
    # tree editing: load sample, add a submenu, move, delete
    pg.click('#btn-sample'); pg.click('button[data-tab="tree"]')
    n0 = len(pg.evaluate('MenuEditor.S.root.items')); pg.click('text=+ submenu'); eq(len(pg.evaluate('MenuEditor.S.root.items')), n0 + 1, 'submenu added at the end of the root')
    pg.click('#list div:has-text("New menu")'); pg.fill('#f-name', 'Extra'); pg.press('#f-name', 'Tab')
    eq(pg.evaluate('MenuEditor.S.root.items[%d].menu' % n0), 'Extra', 'submenu renamed')
    pg.click('#list div:has-text("Extra")'); pg.click('text=+ inline property')
    eq(pg.evaluate('MenuEditor.S.root.items[%d].items.length' % n0), 1, 'inline property added inside the selected submenu')
    pg.click('#list div:has-text("Extra")'); pg.click('button:text-is("up")')
    eq(pg.evaluate('MenuEditor.S.root.items[%d].menu' % (n0 - 1)), 'Extra', 'submenu moved up')
    pg.click('#list div:has-text("Extra")'); pg.click('button:text-is("delete")')
    eq(len(pg.evaluate('MenuEditor.S.root.items')), n0, 'submenu deleted')
    # preset with several values
    pg.click('text=+ preset'); pg.click('#list div:has-text("New preset")'); pg.click('text=+ value')
    check(len(pg.evaluate('Object.keys(MenuEditor.S.root.items[%d].set)' % n0)) == 1, 'a value row was added to the preset')
    # round trip
    out = pg.input_value('#json') if False else pg.evaluate('JSON.stringify(MenuEditor.S)')
    pg.click('#btn-new'); pg.click('button[data-tab="json"]'); pg.fill('#json', out); pg.click('#btn-json-apply'); pg.wait_for_timeout(100)
    eq(pg.evaluate('JSON.stringify(MenuEditor.S)'), out, 'exported JSON loads back unchanged')
    with pg.expect_download() as dl: pg.click('#btn-save')
    saved = open(dl.value.path()).read(); eq(json.loads(saved), json.loads(out), 'downloaded file equals the edited JSON')
    pg.click('#btn-sample'); eq(pg.inner_text('#status-msg'), 'valid', 'sample reloads valid')
    if len(sys.argv) > 1: pg.screenshot(path=sys.argv[1])
    check(not errs, 'no page errors: %s' % errs[:3])
    b.close()
if fails: print('%d check(s) failed' % len(fails)); sys.exit(1)
print('menu editor UI test passed')
