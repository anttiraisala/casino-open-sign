#!/usr/bin/env python3
"""Write tools/plate-designer/arrow-data.js: the geometry of the stick arrow for the Plate Designer.

    python3 tools/generate_plate_designer_arrow.py

Single geometry source stays tools/arrow_geometry.py. The file holds the arrow size, the 10 stick outlines (for
drawing) and the 10 cable-hole positions (drilling) in millimetres, measured from the top-left corner of the arrow.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import arrow_geometry as g

OUTPUT = Path(__file__).resolve().parent / "plate-designer" / "arrow-data.js"


def main():
    sticks, w, h = g.shifted(g.build())
    data = {
        "w": round(w, 2),
        "h": round(h, 2),
        "holeD": g.CABLE_HOLE_D,
        "sticks": [{"name": s.name, "connector": s.connector,
                    "pts": [[round(x, 2) + 0.0, round(y, 2) + 0.0] for x, y in s.body()],
                    "fill": s.fill, "stroke": s.stroke,
                    "hole": [round(s.cx, 2) + 0.0, round(s.cy, 2) + 0.0]} for s in sticks],
    }
    OUTPUT.write_text("// Generated by tools/generate_plate_designer_arrow.py from tools/arrow_geometry.py; do not edit.\n"
                      "var ARROW_DATA = " + json.dumps(data, separators=(",", ":")).replace('{"name"', '\n{"name"') + ";\n"
                      "if (typeof module === 'object' && module.exports) module.exports = ARROW_DATA;\n")
    print("Wrote %s (arrow %.2f x %.2f mm)" % (OUTPUT, w, h))


if __name__ == "__main__":
    main()
